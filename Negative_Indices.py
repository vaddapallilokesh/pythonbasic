#9. Negative indexing

nums = [10,20,30,40,50,60,70]
print("Last:", nums[-1])
print("Second Last:", nums[-2])
print("Last 3:", nums[-3:])

'''output-
Last: 70
Second Last: 60
Last 3: [50, 60, 70]
'''


#10. Reverse with negative step

nums = [1,2,3,4,5]
print("Reverse:", nums[::-1])

#output-Reverse: [5, 4, 3, 2, 1]
