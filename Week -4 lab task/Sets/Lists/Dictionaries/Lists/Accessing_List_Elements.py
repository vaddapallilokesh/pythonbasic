#4. Fruits list

fruits = ["Apple","Banana","Mango","Orange","Grapes","Pineapple","Papaya","Guava"]
print("First:", fruits[0])
print("Last:", fruits[-1])
print("Index 3:", fruits[3])

'''output-
First: Apple
Last: Guava
Index 3: Orange'''


#5. Enumerate list

numbers = [10, 20, 30, 40, 50]
for index, value in enumerate(numbers):
    print("Index:", index, "Value:", value)

'''output-

Index: 0 Value: 10
Index: 1 Value: 20
Index: 2 Value: 30
Index: 3 Value: 40
Index: 4 Value: 50

'''
