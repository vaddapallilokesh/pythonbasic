# conditional, loop, and print
a = 10          
if a > 5:           
    print("a is greater than 5")   

for i in range(3):
    print("Loop iteration:", i)

'''output-
a is greater than 5

Loop iteration: 0
Loop iteration: 1
Loop iteration: 2
'''
    


# 2. Multi-line statement using parentheses
total = (1 + 2 + 3 + 4 + 5 + 6)
print("Total =", total)

#Total = 21


# 3. Multiple statements in one line using semicolon
x = 5; y = 10; print("x+y =", x + y)

#x+y = 15


# Equivalent using implicit continuation with parentheses
sum_val = (x + y + 20)
print("Sum with parentheses =", sum_val)

#output- Sum with parentheses = 35


